(Color, Color, Color, Color, Color, Color, Color) goghThemeColors(
  GoghPreset preset,
) {
  final bg = preset.background;
  final surface = Color.alphaBlend(
    preset.foreground.withValues(alpha: .08),
    bg,
  );
  var fg = preset.foreground;
  double contrast(Color a, Color b) {
    final x = a.computeLuminance();
    final y = b.computeLuminance();
    return ((x > y ? x : y) + .05) / ((x > y ? y : x) + .05);
  }

  final target = bg.computeLuminance() > .5 ? Colors.black : Colors.white;
  for (
    var i = 0;
    i < 20 && (contrast(fg, bg) < 4.5 || contrast(fg, surface) < 4.5);
    i++
  ) {
    fg = Color.lerp(fg, target, .1)!;
  }
  return preset.light
      ? (
          const Color(0xFF1B1D25),
          const Color(0xFF2B2E38),
          const Color(0xFFF2F2F2),
          preset.accent,
          bg,
          surface,
          fg,
        )
      : (
          bg,
          surface,
          fg,
          preset.accent,
          const Color(0xFFF7F8FA),
          const Color(0xFFE9EBEF),
          const Color(0xFF20242C),
        );
}
